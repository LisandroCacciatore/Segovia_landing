export const getPostBySlug = (slug) =>
  blogPosts.find((p) => p.slug === slug);

export const getPostsByCategory = (categoryId) =>
  categoryId === 'all'
    ? blogPosts
    : blogPosts.filter((p) => p.category === categoryId);

export const getRelatedPosts = (currentSlug, category, limit = 3) => {
  // Primero los enlaces internos definidos a mano (los que pidio el estudio);
  // si el articulo no tiene, se cae a la misma categoria.
  const actual = blogPosts.find((p) => p.slug === currentSlug);
  const explicitos = (actual && actual.related) || [];
  const porSlug = blogPosts.filter((p) => explicitos.includes(p.slug));
  if (porSlug.length > 0) return porSlug.slice(0, limit);
  return blogPosts
    .filter((p) => p.slug !== currentSlug && p.category === category)
    .slice(0, limit);
};

export const getSortedPosts = () =>
  [...blogPosts].sort((a, b) => new Date(b.date) - new Date(a.date));
